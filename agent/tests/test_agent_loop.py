import json
from decimal import Decimal

import pytest

from tests.fakes import FakeApi, FakePolicies, ScriptedLLM, calls, says, tool_call
from tuition_agent.agent import PaymentSummary, TuitionAgent
from tuition_agent.trace import format_trace, save_trace


def _agent(llm: ScriptedLLM, confirm=lambda summary: False, max_steps: int = 6):
    api, policies = FakeApi(), FakePolicies()
    confirmations: list[PaymentSummary] = []

    def record_confirm(summary: PaymentSummary) -> bool:
        confirmations.append(summary)
        return confirm(summary)

    agent = TuitionAgent(llm=llm, api=api, policies=policies, confirm_payment=record_confirm,
                         llm_label="scripted", max_steps=max_steps)
    return agent, api, policies, confirmations


# --- Loop ----------------------------------------------------------------------------------------

def test_tool_results_are_sent_back_to_the_llm():
    llm = ScriptedLLM(calls(tool_call("get_my_tuition", call_id="c1")), says("Your balance is 6000.00 USD."))
    agent, *_ = _agent(llm)

    trace = agent.ask("What is my balance?")

    assert trace.final_answer == "Your balance is 6000.00 USD."
    second_request = llm.calls[1]
    assert second_request[-2]["tool_calls"][0]["function"]["name"] == "get_my_tuition"
    tool_message = second_request[-1]
    assert tool_message["role"] == "tool" and tool_message["tool_call_id"] == "c1"
    assert json.loads(tool_message["content"])["balance"] == 6000.0


def test_answer_without_tools_ends_after_one_llm_call():
    agent, *_ = _agent(ScriptedLLM(says("Hello! How can I help?")))

    trace = agent.ask("hi")

    assert trace.tool_calls == []
    assert trace.llm_calls == 1


def test_multiple_tool_calls_in_one_turn_are_all_executed():
    llm = ScriptedLLM(
        calls(tool_call("get_my_tuition", call_id="a"),
              tool_call("search_tuition_policies", {"query": "installments"}, call_id="b")),
        says("You are eligible to request installments (Policy §3.1)."),
    )
    agent, _, policies, _ = _agent(llm)

    trace = agent.ask("Can I pay my outstanding balance in installments?")

    assert [e.tool for e in trace.tool_calls] == ["get_my_tuition", "search_tuition_policies"]
    assert policies.queries == [("installments", 3)]
    assert [m["tool_call_id"] for m in llm.calls[1] if m["role"] == "tool"] == ["a", "b"]


def test_conversation_history_is_kept_between_questions():
    llm = ScriptedLLM(says("First answer"), says("Second answer"))
    agent, *_ = _agent(llm)

    agent.ask("first")
    agent.ask("second")

    roles = [m["role"] for m in llm.calls[1]]
    assert roles == ["system", "user", "assistant", "user"]


def test_loop_stops_after_max_steps():
    llm = ScriptedLLM(*[calls(tool_call("get_my_tuition", call_id=f"c{i}")) for i in range(3)])
    agent, *_ = _agent(llm, max_steps=3)

    trace = agent.ask("loop forever")

    assert len(trace.tool_calls) == 3
    assert "could not complete" in trace.final_answer


@pytest.mark.parametrize(
    ("call", "code"),
    [
        (tool_call("delete_everything"), "UNKNOWN_TOOL"),
        (tool_call("pay_tuition", raw='{"term": '), "INVALID_ARGUMENTS"),
        (tool_call("search_tuition_policies", {"query": ""}), "INVALID_ARGUMENTS"),
    ],
)
def test_bad_tool_calls_return_errors_to_the_llm(call, code):
    agent, *_ = _agent(ScriptedLLM(calls(call), says("Sorry.")))

    trace = agent.ask("do something")

    assert trace.tool_calls[0].result["error"]["code"] == code


# --- Payment confirmation ------------------------------------------------------------------------

def test_payment_with_yes_is_submitted_with_agent_generated_transaction_id():
    llm = ScriptedLLM(calls(tool_call("pay_tuition", {"term": "2026-FALL", "amount": 500})), says("Paid."))
    agent, api, _, confirmations = _agent(llm, confirm=lambda s: True)

    trace = agent.ask("Pay 500 for fall")

    assert confirmations == [PaymentSummary("20230001", "2026-FALL", Decimal("500.00"), Decimal("3000.00"), "USD")]
    assert confirmations[0].remaining_after == Decimal("2500.00")
    term, amount, transaction_id = api.payments[0]
    assert (term, amount) == ("2026-FALL", Decimal("500.00"))
    assert len(transaction_id) == 36  # UUID generated by the agent, not by the LLM
    entry = trace.tool_calls[0]
    assert entry.confirmation == "yes"
    assert entry.result["status"] == "SUCCESS"


def test_payment_without_yes_is_not_submitted():
    llm = ScriptedLLM(calls(tool_call("pay_tuition", {"term": "2026-FALL", "amount": 500})), says("Cancelled."))
    agent, api, _, confirmations = _agent(llm, confirm=lambda s: False)

    trace = agent.ask("Pay 500 for fall")

    assert len(confirmations) == 1
    assert api.payments == []
    assert trace.tool_calls[0].confirmation == "no"
    assert trace.tool_calls[0].result["status"] == "CANCELLED"


@pytest.mark.parametrize(
    ("arguments", "code"),
    [
        ({"term": "2026-FALL", "amount": 3000.01}, "AMOUNT_EXCEEDS_BALANCE"),
        ({"term": "2030-FALL", "amount": 10}, "TUITION_NOT_FOUND"),
        ({"term": "fall", "amount": 10}, "INVALID_ARGUMENTS"),
        ({"term": "2026-FALL", "amount": -5}, "INVALID_ARGUMENTS"),
        ({"term": "2026-FALL", "amount": 10.555}, "INVALID_ARGUMENTS"),
        ({"term": "2026-FALL", "amount": "abc"}, "INVALID_ARGUMENTS"),
    ],
)
def test_invalid_payments_are_rejected_before_asking_the_user(arguments, code):
    llm = ScriptedLLM(calls(tool_call("pay_tuition", arguments)), says("Cannot pay."))
    agent, api, _, confirmations = _agent(llm, confirm=lambda s: True)

    trace = agent.ask("pay")

    assert confirmations == []
    assert api.payments == []
    assert trace.tool_calls[0].result["error"]["code"] == code


