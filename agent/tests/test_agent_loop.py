def test_trace_records_tools_inputs_results_answer_and_usage(tmp_path):
    llm = ScriptedLLM(calls(tool_call("search_tuition_policies", {"query": "deadline", "top_k": 2})),
                      says("The Fall deadline is September 30, 2026 (Policy §2.1)."))
    agent, *_ = _agent(llm)

    trace = agent.ask("When is the payment deadline?")
    path = save_trace(trace, tmp_path)

    saved = json.loads(path.read_text(encoding="utf-8"))
    assert saved["question"] == "When is the payment deadline?"
    assert saved["student_no"] == "20230001"
    assert saved["tool_calls"][0]["tool"] == "search_tuition_policies"
    assert saved["tool_calls"][0]["input"] == {"query": "deadline", "top_k": 2}
    assert saved["tool_calls"][0]["result"]["matches"][0]["section"] == "3.1"
    assert saved["final_answer"].endswith("(Policy §2.1).")
    assert saved["token_usage"] == {"prompt_tokens": 200, "completion_tokens": 30}
    assert path.name.startswith("agent_") and "when-is-the-payment-deadline" in path.name
    assert "search_tuition_policies" in format_trace(trace)
